// The track is generated by sim.c, exactly as a CPU worker does it, then
// every array the step reads is flattened into three GPU buffers.
function buildAndUploadTrack(d) {
    const nPts = Math.min(d.path.length, ex.max_path_pts());
    const pIn = f32v(ex.path_in_ptr(), Math.max(1, nPts * 4));
    for (let i = 0; i < nPts; i++) {
        const p = d.path[i];
        pIn[i * 4] = p.x; pIn[i * 4 + 1] = p.y;
        pIn[i * 4 + 2] = p.type === 'corner' ? 1 : 0;
        pIn[i * 4 + 3] = p.radius !== undefined ? p.radius : 60;
    }
    const zones = d.zones || [];
    const nz = Math.min(zones.length, ex.max_zones());
    const zIn = f32v(ex.zone_in_ptr(), Math.max(1, nz * 5));
    const ZID = { speed: 0, precision: 1, focus: 2, spawnkill: 3 };
    for (let i = 0; i < nz; i++) {
        const z = zones[i];
        zIn[i * 5] = z.x; zIn[i * 5 + 1] = z.y; zIn[i * 5 + 2] = z.radius;
        zIn[i * 5 + 3] = ZID[z.type] !== undefined ? ZID[z.type] : -1;
        zIn[i * 5 + 4] = z.killTimer !== undefined ? z.killTimer : 150;
    }
    const hasStart = d.startPos ? 1 : 0;
    const hasAngle = (d.startAngle !== undefined && d.startAngle !== null) ? 1 : 0;
    ex.track_build(ex.path_in_ptr(), nPts, d.width,
        hasStart, hasStart ? d.startPos.x : 0, hasStart ? d.startPos.y : 0,
        hasAngle, hasAngle ? d.startAngle : 0, ex.zone_in_ptr(), nz,
        d.autoWidth ? 1 : 0, d.autoWidthBlend || 0);

    // Views only after the build: it can grow memory, which detaches them.
    const tp = ex.track_info();
    const t = new Uint32Array(memory.buffer, tp, 32), tfl = new Float32Array(memory.buffer, tp, 32);
    trk.cpN = t[0] | 0; trk.startCp = t[1] | 0; trk.zoneN = t[2] | 0; trk.centerN = t[3] | 0;
    trk.gridNx = t[4] | 0; trk.gridNy = t[5] | 0; trk.hasGrid = t[8] | 0; trk.hasBuckets = t[9] | 0;
    trk.gridCell = tfl[25]; trk.gridOx = tfl[26]; trk.gridOy = tfl[27]; trk.trackLen = tfl[28]; trk.wMax = tfl[29];
    const nGridItems = trk.hasGrid ? t[6] : 0, nWalls = trk.hasBuckets ? t[7] : 0;

    const walls = new Float32Array(Math.max(8, nWalls * 8));
    if (nWalls) {
        const cols = [11, 12, 13, 14, 15, 16, 17, 18].map(k => f32v(t[k], nWalls));
        for (let w = 0; w < nWalls; w++) for (let j = 0; j < 8; j++) walls[w * 8 + j] = cols[j][w];
    }

    trk.zoneOff = trk.cpN * 6;
    trk.ctrOff = trk.zoneOff + trk.zoneN * 5;
    trk.wOff = trk.ctrOff + trk.centerN * 2;
    const tfArr = new Float32Array(Math.max(4, trk.wOff + trk.centerN));
    if (trk.cpN > 0) {
        const cps = f32v(t[19], trk.cpN * 7);   // 6 floats + an int apex flag each
        for (let i = 0; i < trk.cpN; i++) for (let j = 0; j < 6; j++) tfArr[i * 6 + j] = cps[i * 7 + j];
    }
    if (trk.zoneN > 0) {
        const zf = f32v(t[20], trk.zoneN * 5), zi = i32v(t[20], trk.zoneN * 5);
        for (let i = 0; i < trk.zoneN; i++) {
            const o = trk.zoneOff + i * 5;
            tfArr[o] = zf[i * 5]; tfArr[o + 1] = zf[i * 5 + 1]; tfArr[o + 2] = zf[i * 5 + 2];
            tfArr[o + 3] = zi[i * 5 + 3]; tfArr[o + 4] = zf[i * 5 + 4];
        }
    }
    if (trk.centerN > 0) {
        tfArr.set(f32v(t[21], trk.centerN * 2), trk.ctrOff);
        if (t[22]) tfArr.set(f32v(t[22], trk.centerN), trk.wOff);
    }

    const nB = trk.hasBuckets ? trk.cpN + 1 : 2;
    const nCells = trk.hasGrid ? trk.gridNx * trk.gridNy + 1 : 0;
    trk.gsOff = nB; trk.giOff = nB + nCells;
    const tiArr = new Int32Array(Math.max(4, trk.giOff + nGridItems));
    if (trk.hasBuckets) tiArr.set(i32v(t[10], trk.cpN + 1), 0);
    if (trk.hasGrid) {
        tiArr.set(i32v(t[23], nCells), trk.gsOff);
        if (nGridItems) tiArr.set(i32v(t[24], nGridItems), trk.giOff);
    }

    device.queue.writeBuffer(ensure('walls', walls.byteLength, STORAGE_IN), 0, walls);
    trackTiOff = tfArr.length;
    trackTD = new Float32Array(tfArr.length + tiArr.length);
    trackTD.set(tfArr, 0);
    new Int32Array(trackTD.buffer).set(tiArr, trackTiOff);
    uploadTD();
    writeParams();
}

// Track tables then brains, in the one read-only buffer the shader reads both
// from. The brains' offset follows the track's size, so either changing means
// writing both.
function uploadTD() {
    const nBrains = popN * stride;
    const buf = ensure('td', (trackTD.length + nBrains) * 4, STORAGE_IN);
    device.queue.writeBuffer(buf, 0, trackTD);
    if (nBrains) device.queue.writeBuffer(buf, trackTD.length * 4, lastBrains, 0, nBrains);
}

// `forceLanes` is for tools/gpuparity.mjs only: it pins threads-per-car so
// the test can prove every split lands on the same bits.
function uploadPopulation(brainsF32, stateU32, alive, gate, forceLanes) {
    stride = ex.brain_stride();
    lastBrains = brainsF32;
    uploadTD();
    const cars = ensure('cars', popN * CAR_BYTES, GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST | GPUBufferUsage.COPY_SRC);
    if (popN) device.queue.writeBuffer(cars, 0, stateU32, 0, popN * STATE_WORDS);
    ensureStaging(popN * CAR_BYTES);
    mirror = stateU32.slice(0, popN * STATE_WORDS);
    lanes = forceLanes || lanesFor(popN);
    resetAux(alive, gate);
    writeParams();
}

// The start-of-run state comes from sim.c's own pop_reset, so a car spawns
