function aliveIn(state) {
    const s = new Int32Array(state.buffer, state.byteOffset, state.length);
    let n = 0;
    for (let c = 0; c < popN; c++) if (s[c * STATE_WORDS + 7] === 0) n++;
    return n;
}

async function mapRead(buf, bytes) {
    await buf.mapAsync(GPUMapMode.READ, 0, bytes);
    const out = buf.getMappedRange(0, bytes).slice(0);
    buf.unmap();
    return out;
}

async function simulate(iters, budgetMs) {
    if (bindDirty) rebuildBindGroup();
    const deadline = performance.now() + budgetMs;
    let executed = 0;
    const pipe = pipes.get(lanes);
    const nWG = Math.ceil(popN / (WG / lanes));
    device.queue.writeBuffer(bufs.aux, 0, new Int32Array([INT_MAX]));
    let remaining = iters, stopped = false;
    const inflight = [];
    while (remaining > 0 && !stopped) {
        const n = Math.min(SUB_STEPS, remaining);
        remaining -= n;
        executed += n;
        const enc = device.createCommandEncoder();
        const pass = enc.beginComputePass();
        pass.setPipeline(pipe);
        pass.setBindGroup(0, bindGroup);
        for (let s = 0; s < n; s++) pass.dispatchWorkgroups(nWG);
        pass.end();
        let probe = null;
        if (remaining > 0) {
            probe = probePool.pop() || device.createBuffer({ size: 16, usage: GPUBufferUsage.MAP_READ | GPUBufferUsage.COPY_DST });
            enc.copyBufferToBuffer(bufs.aux, 0, probe, 0, 16);
        }
        device.queue.submit([enc.finish()]);
        if (probe) inflight.push({ buf: probe, done: probe.mapAsync(GPUMapMode.READ) });
        if (inflight.length >= PROBE_DEPTH) {
            const p = inflight.shift();
            await p.done;
            const v = new Int32Array(p.buf.getMappedRange(0, 8));
            stopped = v[0] !== INT_MAX || v[1] <= 0 || performance.now() > deadline;
            p.buf.unmap();
            probePool.push(p.buf);
        }
    }
    const bytes = popN * CAR_BYTES;
    const enc = device.createCommandEncoder();
    enc.copyBufferToBuffer(bufs.cars, 0, stateStaging, 0, bytes);
    enc.copyBufferToBuffer(bufs.aux, 0, auxStaging, 0, AUX_BYTES);
    device.queue.submit([enc.finish()]);
    const [stateBuf, auxBuf] = await Promise.all([mapRead(stateStaging, bytes), mapRead(auxStaging, AUX_BYTES)]);
    for (const p of inflight) { await p.done; p.buf.unmap(); probePool.push(p.buf); }
    const a = new Int32Array(auxBuf);
    crashMirror = a.slice(4, 4 + MAX_GATES);
    gateMirror = new Float32Array(auxBuf, (4 + MAX_GATES) * 4, MAX_GATES).slice();
    return { state: new Uint32Array(stateBuf), stopFrame: a[0], executed };
}

// One 'run' round: step, then answer in exactly the shape sim-worker.js
// does, down to the CPU build's rules for maxLaps, allCrashed and the step
// count, so engine.js and the evolve trigger can't tell the two apart.
async function run(msg) {
    const t0 = performance.now();
    const iters = msg.iters | 0;
    const before = new Int32Array(mirror.buffer, mirror.byteOffset, mirror.length);
    let aliveStart = 0, f0 = 0;
    for (let c = 0; c < popN; c++) if (before[c * STATE_WORDS + 7] === 0) { aliveStart++; f0 = before[c * STATE_WORDS + 9]; }

    let after = before, stopFrame = INT_MAX, executed = 0;
    if (aliveStart > 0 && iters > 0 && !lost) {
        try {
            // budgetMs is for tools/gpuparity.mjs, which wants whole chunks.
            const r = await simulate(iters, msg.budgetMs || ROUND_BUDGET_MS);
            mirror = r.state;
            after = new Int32Array(mirror.buffer, mirror.byteOffset, mirror.length);
            stopFrame = r.stopFrame;
            executed = r.executed;
        } catch (e) {
            // Device lost mid-chunk (driver reset, tab backgrounded on some
            // mobile GPUs). No progress this round; the engine is told
            // separately and moves the population back to the CPU from the
            // last good state.
            if (!lost) { lost = true; self.postMessage({ type: 'gpu-lost', index, message: String(e && e.message || e) }); }
        }
    }

    const af = new Float32Array(mirror.buffer, mirror.byteOffset, mirror.length);
    let steps = 0, maxLaps = 0, alive = 0, lastCrash = 0;
    for (let c = 0; c < popN; c++) {
        const o = c * STATE_WORDS;
        if (after[o + 7] === 0) alive++;
        if (before[o + 7] !== 0) continue;
        steps += after[o + 9] - before[o + 9];
        if (after[o + 11] > maxLaps) maxLaps = after[o + 11];
        if (after[o + 9] > lastCrash) lastCrash = after[o + 9];
    }
    // As sim.c's run(executed): all-crashed only if some step began with no
    // car left to move — not when the last one went on the final step.
    const allCrashed = iters <= 0 || aliveStart === 0 ||
        (alive === 0 && stopFrame === INT_MAX && lastCrash < f0 + executed);

    let buffer;
    const stride5 = 5;
    if (msg.wantRender) {
        const len = popN * 18;
        buffer = msg.recycle && msg.recycle.byteLength === len * 4 ? new Float32Array(msg.recycle) : new Float32Array(len);
        for (let c = 0; c < popN; c++) {
            const o = c * STATE_WORDS, r = c * 18;
            buffer[r] = popStart + c; buffer[r + 1] = after[o + 7] ? 1 : 0;
            buffer[r + 2] = af[o]; buffer[r + 3] = af[o + 1]; buffer[r + 4] = af[o + 2]; buffer[r + 5] = af[o + 5];
            buffer[r + 6] = af[o + 18]; buffer[r + 7] = af[o + 19];
            buffer[r + 8] = after[o + 11]; buffer[r + 9] = af[o + 6]; buffer[r + 10] = af[o + 13];
            for (let k = 0; k < 7; k++) buffer[r + 11 + k] = af[o + 20 + k];
        }
    } else {
        const len = popN * stride5;
        buffer = msg.recycle && msg.recycle.byteLength === len * 4 ? new Float32Array(msg.recycle) : new Float32Array(len);
        for (let c = 0; c < popN; c++) {
            const o = c * STATE_WORDS, r = c * stride5;
            buffer[r] = af[o + 6]; buffer[r + 1] = after[o + 11]; buffer[r + 2] = af[o + 13];
            buffer[r + 3] = after[o + 12]; buffer[r + 4] = after[o + 15];
        }
    }
    const crashCount = crashMirror.slice();
    const gateRatio = popStart === 0 ? gateMirror.slice() : null;
    const transfer = [buffer.buffer, crashCount.buffer];
    if (gateRatio) transfer.push(gateRatio.buffer);
    self.postMessage({
        type: 'done', index, start: popStart, count: popN,
        maxLaps, allCrashed, alive, busyMs: performance.now() - t0, carSteps: steps, crashCount,
        render: !!msg.wantRender, stride: stride5, buffer, gateRatio
    }, transfer);
}

async function handle(msg) {
    switch (msg.type) {
        case 'init': {
            index = msg.index;
            const instance = await WebAssembly.instantiate(msg.module, {});
            ex = instance.exports;
            memory = ex.memory;
            try {
                await initGPU();
            } catch (e) {
                self.postMessage({ type: 'gpu-error', index, message: String(e && e.message || e) });
                return;
            }
            self.postMessage({ type: 'ready', index, gpu: adapterLabel });
            return;
        }
        case 'config':
            applyConfig(msg.args);
            writeParams();
            return;
        case 'track':
            applyConfig(msg.config);
            buildAndUploadTrack(msg.def);
            return;
        case 'pop': {
            popStart = msg.start; popN = msg.count; hidden = msg.hidden;
            ex.pop_init(popN, popStart, hidden, msg.seed);
            if (msg.focused) i32v(ex.car_focused_ptr(), popN).set(msg.focused.subarray(0, popN));
            focusLo = msg.focusLo === undefined ? -1 : msg.focusLo;
            focusHi = msg.focusHi === undefined ? -1 : msg.focusHi;
            ex.set_focus_window(focusLo, focusHi);
            ex.pop_reset();
            lastBrains = msg.brains.slice(0, popN * ex.brain_stride());
            uploadPopulation(lastBrains, packFromWasm(), popN, null, msg.lanes);
            return;
        }
        case 'reset':
            ex.pop_reset();
            uploadPopulation(lastBrains, packFromWasm(), popN, null, lanes);
            return;
        case 'import': {
            popStart = msg.start; popN = msg.count; hidden = msg.hidden;
            ex.pop_init(popN, popStart, hidden, msg.seed);
            focusLo = msg.focusLo === undefined ? -1 : msg.focusLo;
            focusHi = msg.focusHi === undefined ? -1 : msg.focusHi;
            ex.set_focus_window(focusLo, focusHi);
            // Mirror the imported cars into wasm too, so a later 'reset'
            // (which rebuilds the start state there) keeps their focus flags.
            new Uint32Array(memory.buffer, ex.state_ptr(), popN * STATE_WORDS).set(msg.state);
            ex.unpack_state();
            lastBrains = msg.brains.slice(0, popN * ex.brain_stride());
            uploadPopulation(lastBrains, msg.state, aliveIn(msg.state), msg.gateRatio || null, msg.lanes);
            return;
        }
        case 'run':
            await run(msg);
            return;
        case 'export': {
            const state = mirror.slice();
            const crashCount = crashMirror.slice();
            const gateRatio = popStart === 0 ? gateMirror.slice() : null;
            const transfer = [state.buffer, crashCount.buffer];
            if (gateRatio) transfer.push(gateRatio.buffer);
            self.postMessage({ type: 'exported', index, start: popStart, count: popN, state, crashCount, gateRatio }, transfer);
            return;
        }
    }
}

// The current slice's brains, kept host-side so a 'reset' (which re-uploads
// the whole start-of-run population) doesn't need them sent again.
let lastBrains = new Float32Array(0);

// Strictly one message at a time. 'run' awaits the GPU, and without this a
// 'config' or 'pop' arriving meanwhile would interleave with it — the CPU
// worker gets this ordering for free by being synchronous.
let queue = Promise.resolve();
self.onmessage = e => {
    const msg = e.data;
    queue = queue.then(() => handle(msg)).catch(err => {
        const message = String(err && err.message || err);
        if (msg.type === 'init') self.postMessage({ type: 'gpu-error', index, message });
        else { console.error('gpu-worker:', err); if (!lost) { lost = true; self.postMessage({ type: 'gpu-lost', index, message }); } }
    });
};
