// gpu-worker.js — the WebGPU backend. One of these replaces the whole pool of
// sim-worker.js instances when the Compute toggle is on GPU, and it speaks
// exactly the same message protocol ('init', 'config', 'track', 'pop',
// 'reset', 'run', 'export', 'import'), so engine.js treats it as a pool of
// one and nothing above the engine knows the difference.
//
// WHAT RUNS WHERE, AND WHY
// Each simulation step is strictly sequential for a car — sensors feed the
// network, the network drives the physics, the physics decides the next
// sensors — so moving any single piece (the neural network, say) to the GPU
// on its own would need a CPU<->GPU round trip every step, and a round trip
// costs far more than the ~65 multiply-adds the network actually is. The only
// split that pays is the whole step: walls, raycasts, network, physics,
// gates, laps and fitness all run in the compute shader below, the population
// stays resident in GPU memory for the whole generation, and the only traffic
// is one small uniform write per chunk going in and one readback of the car
// state coming out (≈128 bytes a car). Evolution stays on the CPU — it runs
// once a generation, needs every car's fitness, and that readback is already
// happening anyway. Track geometry is still generated by sim.c (this worker
// hosts a wasm instance for exactly that, and for building the start-of-run
// car state), then uploaded once per track.
//
// LOCKSTEP. A generation ends the moment any car completes the target lap
// count, at a step boundary, for every car at once. So each step is its own
// dispatch — consecutive dispatches in a WebGPU pass are ordered, which is
// the one global barrier a GPU offers — and a car that finishes its laps
// records the frame it happened on (stopFrame), which every car checks
// before it steps. Cars that would run past that frame don't. Hyper mode's
// big chunks are submitted in sub-batches with a tiny pipelined probe of that
// flag, so once the generation is over the rest of the chunk isn't even
// submitted.
//
// PARALLELISM. A small population (a phone's 150 cars) is nowhere near
// enough threads to keep a GPU busy, and each car's wall scan is the long
// pole of a step. So up to eight threads share one car: they split that car's
// wall bucket between them, each keeps its own seven ray minima and collision
// flag, and one of them combines the eight results through workgroup memory
// and does the (short) rest of the step. How many threads per car is picked
// from the population size (see lanesFor) so there are always roughly two
// thousand in flight; the result is bit-identical whichever is picked, since
// min() and "any hit" don't depend on order.
//
// NUMERICS. WGSL has no f64 and its built-in sin/cos/atan2 are only
// guaranteed to a few thousandths on [-pi, pi] — and a car's heading is never
// wrapped, so it drifts far outside that. The trig below is therefore done by
// hand in f32 (Cody-Waite reduction + minimax polynomials, ~1 ulp), and the
// network's tanh is the exact same f32 routine sim.c uses. The result tracks
// the CPU build to within f32 rounding, not bit for bit — tools/gpuparity.mjs
// is what holds it to that.

