// Grow-only: a buffer is replaced only when it is too small, so a
// generation-to-generation run at the same population size never allocates.
function ensure(name, bytes, usage) {
    const need = Math.max(16, Math.ceil(bytes / 16) * 16);
    if (bufs[name] && bufs[name].size >= need) return bufs[name];
    if (bufs[name]) bufs[name].destroy();
    bufs[name] = device.createBuffer({ size: need, usage });
    bindDirty = true;
    return bufs[name];
}
function ensureStaging(bytes) {
    const need = Math.max(16, Math.ceil(bytes / 16) * 16);
    if (stateStaging && stateStaging.size >= need) return;
    if (stateStaging) stateStaging.destroy();
    stateStaging = device.createBuffer({ size: need, usage: GPUBufferUsage.MAP_READ | GPUBufferUsage.COPY_DST });
}

// Guarded: on a browser without WebGPU the constant doesn't exist, and this
// file still has to load far enough to report that back as a 'gpu-error'.
const STORAGE_IN = typeof GPUBufferUsage !== 'undefined' ? GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST : 0;

async function initGPU() {
    if (typeof navigator === 'undefined' || !navigator.gpu) throw new Error('WebGPU is not available in this browser');
    // A full ("core") adapter if there is one; otherwise compatibility mode,
    // which is how a GPU without Vulkan/Metal/D3D12 (an older Android phone
    // on OpenGL ES) exposes compute at all. Browsers that don't know the
    // featureLevel option just ignore it.
    let adapter = await navigator.gpu.requestAdapter({ powerPreference: 'high-performance' });
    if (!adapter) adapter = await navigator.gpu.requestAdapter({ powerPreference: 'high-performance', featureLevel: 'compatibility' });
    if (!adapter) throw new Error('no WebGPU adapter — the GPU may be blocklisted or disabled');
    const info = adapter.info || {};
    adapterLabel = [info.vendor, info.architecture].filter(Boolean).join(' ') || 'WebGPU';
    // A software adapter runs the shader on the CPU, slower than the wasm
    // path it would replace; allowed, but labelled so nobody is misled.
    if (info.isFallbackAdapter || adapter.isFallbackAdapter) adapterLabel += ' (software)';
    device = await adapter.requestDevice();
    device.lost.then(li => {
        lost = true;
        if (li.reason !== 'destroyed') self.postMessage({ type: 'gpu-lost', index, message: li.message || 'GPU device lost' });
    });

    const module = device.createShaderModule({ code: WGSL });
    const ci = await module.getCompilationInfo();
    const errs = ci.messages.filter(m => m.type === 'error');
    if (errs.length) throw new Error('shader: ' + errs.map(m => `${m.lineNum}:${m.linePos} ${m.message}`).join('; '));

    const storage = (binding, type) => ({ binding, visibility: GPUShaderStage.COMPUTE, buffer: { type } });
    bindLayout = device.createBindGroupLayout({ entries: [
        { binding: 0, visibility: GPUShaderStage.COMPUTE, buffer: { type: 'uniform' } },
        storage(1, 'read-only-storage'), storage(2, 'read-only-storage'),
        storage(3, 'storage'), storage(4, 'storage')
    ] });
    const layout = device.createPipelineLayout({ bindGroupLayouts: [bindLayout] });
    // All four variants up front, in parallel, while the CPU pool is still
    // the one running — so changing population size later never stalls on a
    // shader compile.
    await Promise.all([1, 2, 4, 8].map(async l => {
        pipes.set(l, await device.createComputePipelineAsync({
            layout, compute: { module, entryPoint: 'step', constants: { LANES: l } }
        }));
    }));

    bufs.params = device.createBuffer({ size: 144, usage: GPUBufferUsage.UNIFORM | GPUBufferUsage.COPY_DST });
    bufs.aux = device.createBuffer({ size: AUX_BYTES, usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST | GPUBufferUsage.COPY_SRC });
    auxStaging = device.createBuffer({ size: AUX_BYTES, usage: GPUBufferUsage.MAP_READ | GPUBufferUsage.COPY_DST });
    for (const n of ['walls', 'td']) ensure(n, 16, GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST);
    ensure('cars', CAR_BYTES, GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST | GPUBufferUsage.COPY_SRC);
    ensureStaging(CAR_BYTES);
    resetAux(0, null);
    writeParams();
}

function rebuildBindGroup() {
    bindGroup = device.createBindGroup({ layout: bindLayout, entries: [
        { binding: 0, resource: { buffer: bufs.params } },
        { binding: 1, resource: { buffer: bufs.walls } },
        { binding: 2, resource: { buffer: bufs.td } },
        { binding: 3, resource: { buffer: bufs.cars } },
        { binding: 4, resource: { buffer: bufs.aux } }
    ] });
    bindDirty = false;
}

function resetAux(alive, gate) {
    const a = new Int32Array(AUX_WORDS);
    a[0] = INT_MAX; a[1] = alive;
    const g = new Float32Array(a.buffer, (4 + MAX_GATES) * 4, MAX_GATES);
    if (gate) g.set(gate); else g.fill(-1);
    device.queue.writeBuffer(bufs.aux, 0, a);
    crashMirror = new Int32Array(MAX_GATES);
    gateMirror = g.slice();
}

